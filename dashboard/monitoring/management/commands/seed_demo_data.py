"""
monitoring/management/commands/seed_demo_data.py

Usage:
    python manage.py seed_demo_data
    python manage.py seed_demo_data --flush   # wipes existing demo data first

Creates a realistic spread of MSMEs and projects across every status,
covering the scenarios you'd actually want to click through while testing:
  - a stalled pending application (>1 year old — is_pending_delinquent)
  - a Phase I project running late (is_phase1_delayed)
  - a Phase II project that's current on payments
  - a Phase II project a few months behind (is_refund_delinquent)
  - a Phase II project 6+ months behind (the collection-action threshold)
  - a Phase II project that's been restructured
  - a Phase II project that's nearly fully refunded
  - completed, terminated, and withdrawn projects
  - two MSMEs that are deliberately INELIGIBLE for new iFund (one for
    outstanding accountabilities, one for Filipino ownership under 60%)
    so Cooperator.is_eligible_for_new_ifund has something to actually flag

Deliberately does NOT hand-create ProjectRequirement rows — those are
auto-generated by monitoring/signals.py the moment a project is created or
advances a phase, exactly as they would be for a real project. This command
instead marks a realistic subset of the auto-created rows as submitted, and
steps each project through its real status sequence via .save() calls (not
a single field assignment) so the refund-schedule-generation signal fires
naturally too.

File fields (photo, requirement/report files, receipts, supporting
documents) are deliberately left EMPTY — attaching and testing file uploads
is exactly the kind of thing you'll want to click through by hand in the
running app, not something worth faking with placeholder bytes here.
"""

